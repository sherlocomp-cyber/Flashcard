type AttrValue = string | number | boolean | undefined | null | ((event: Event) => void);
type Child = Node | string | null | undefined | false;

const PROPS = new Set(['value', 'checked', 'disabled', 'hidden', 'selected', 'multiple']);

/** Pembuat elemen kecil: atribut `onXxx` menjadi pendengar peristiwa, `class` menjadi className. */
export function h<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  attrs: Record<string, AttrValue> = {},
  ...children: Child[]
): HTMLElementTagNameMap[K] {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs)) {
    if (value === undefined || value === null || value === false) continue;
    if (typeof value === 'function') {
      el.addEventListener(key.slice(2).toLowerCase(), value);
    } else if (key === 'class') {
      el.className = String(value);
    } else if (PROPS.has(key)) {
      (el as unknown as Record<string, unknown>)[key] = value;
    } else {
      el.setAttribute(key, value === true ? '' : String(value));
    }
  }
  for (const child of children) {
    if (child === null || child === undefined || child === false) continue;
    el.append(child);
  }
  return el;
}

